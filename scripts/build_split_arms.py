#!/usr/bin/env python
"""Build the half-dose "split" arms that test whether which rows are chosen matters.

For every source arm (2073 rows) the script writes several 1036-row files under
datasets/arms/splits/ plus a training config per file under
configs/weekend/splits/:

  <src>-rand      random half (seed 42)                  control
  <src>-lowcov    1036 lowest  idf_coverage (Stanza lemma overlap query/positive)
  <src>-highcov   1036 highest idf_coverage
  <src>-hard      1036 highest loss_own under the base model (pos vs own negatives)
  <src>-easy      1036 lowest  loss_own

Coverage splits need results/lexical_difficulty/full/<src>.jsonl, loss splits need
results/base_loss/<src>.jsonl (scripts/splade_pair_loss.py --per-row-dir). A split
whose metric file is missing is skipped and reported, so the script can be run
again later. Existing split files are left alone unless --force.

The configs use the ck-warmup-s recipe but 4 epochs, so a half-dose arm sees the
same number of optimizer steps (~130) as a 2073-row arm at 2 epochs.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

HALF = 1036
TEMPLATE = """backend: sentence-transformers
training_type: splade

# Split arm generated by scripts/build_split_arms.py: {desc}
# Half the rows of {src}-2073 at 4 epochs, so the optimizer-step count matches
# the 2-epoch full-dose arms. Recipe otherwise identical to ck-warmup-s.
runs_dir: runs/arm-{name}
timestamp_output_dir: true
save_resolved_config: true

train_data: datasets/arms/splits/{name}.jsonl

dataset_filter: configs/dataset_filters/splade_positive_score_gt_23_50_no_metricx.yaml
dataset_filter_cache_dir: cache/filtered_datasets

architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 4
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 256
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: 4
  batch_sampler: no_duplicates
  gradient_accumulation_steps: 8
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 32
  negatives_per_query: 6
  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005
  splade_activation_stats:
    enabled: false
    sample_size: 128
    batch_size: 16
    interval_steps: 500
    quantization_factor: 100
    include_negatives: true

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return [json.loads(l) for l in fh if l.strip()]


def metric_map(path: Path, key: str, metric: str) -> dict[str, float] | None:
    if not path.exists():
        return None
    out = {}
    for r in read_jsonl(path):
        v = r.get(metric)
        if v is not None:
            out[str(r[key])] = float(v)
    return out


def write_rows(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", nargs="+", default=["fiqa", "squadv2", "trivia", "wikisynth"])
    ap.add_argument("--arms-dir", type=Path, default=Path("datasets/arms"))
    ap.add_argument("--lexical-dir", type=Path, default=Path("results/lexical_difficulty/full"))
    ap.add_argument("--loss-dir", type=Path, default=Path("results/base_loss"))
    ap.add_argument("--config-dir", type=Path, default=Path("configs/weekend/splits"))
    ap.add_argument("--half", type=int, default=HALF)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--manifest", type=Path, default=Path("datasets/arms/splits/manifest.json"))
    args = ap.parse_args()

    manifest = {}
    if args.manifest.exists():
        manifest = json.loads(args.manifest.read_text())
    built, skipped = [], []
    for src in args.sources:
        src_file = args.arms_dir / f"{src}-2073.jsonl"
        if not src_file.exists():
            skipped.append((src, "source file missing")); continue
        rows = read_jsonl(src_file)
        for r in rows:
            r["query_id"] = str(r["query_id"])
        by_id = {r["query_id"]: r for r in rows}
        if len(by_id) != len(rows):
            skipped.append((src, "duplicate query_id")); continue

        cov = metric_map(args.lexical_dir / f"{src}-2073.jsonl", "query_id", "idf_coverage")
        loss = metric_map(args.loss_dir / f"{src}-2073.jsonl", "query_id", "loss_own")

        plans: list[tuple[str, str, list[str] | None]] = []
        rng = random.Random(args.seed)
        ids = list(by_id)
        rng.shuffle(ids)
        plans.append(("rand", "random half, seed %d" % args.seed, ids[: args.half]))
        if cov is None:
            skipped.append((f"{src}-lowcov/highcov", "no lexical metrics"))
        else:
            ranked = sorted((i for i in ids if i in cov), key=lambda i: (cov[i], i))
            plans.append(("lowcov", "lowest idf_coverage (lexically hardest for a BM25-like model)", ranked[: args.half]))
            plans.append(("highcov", "highest idf_coverage", ranked[-args.half :]))
        if loss is None:
            skipped.append((f"{src}-hard/easy", "no base-loss metrics"))
        else:
            ranked = sorted((i for i in ids if i in loss), key=lambda i: (loss[i], i))
            plans.append(("easy", "lowest base-model loss_own (positive already well separated from its negatives)", ranked[: args.half]))
            plans.append(("hard", "highest base-model loss_own", ranked[-args.half :]))

        for tag, desc, chosen in plans:
            name = f"{src}-{tag}"
            out = args.arms_dir / "splits" / f"{name}.jsonl"
            cfg = args.config_dir / f"arm_{name.replace('-', '_')}.yaml"
            if out.exists() and cfg.exists() and not args.force:
                continue
            chosen_rows = [by_id[i] for i in chosen]
            rng2 = random.Random(args.seed + 1)
            rng2.shuffle(chosen_rows)
            write_rows(out, chosen_rows)
            cfg.parent.mkdir(parents=True, exist_ok=True)
            cfg.write_text(TEMPLATE.format(name=name, src=src, desc=desc))
            stats = {"rows": len(chosen_rows), "config": str(cfg), "data": str(out), "desc": desc}
            if tag in ("lowcov", "highcov") and cov:
                vals = sorted(cov[i] for i in chosen)
                stats["idf_coverage_median"] = vals[len(vals) // 2]
            if tag in ("easy", "hard") and loss:
                vals = sorted(loss[i] for i in chosen)
                stats["loss_own_median"] = vals[len(vals) // 2]
            manifest[name] = stats
            built.append(name)

    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, indent=2, ensure_ascii=False))
    print("built:", ", ".join(built) if built else "nothing new")
    for what, why in skipped:
        print(f"skipped {what}: {why}")


if __name__ == "__main__":
    main()
