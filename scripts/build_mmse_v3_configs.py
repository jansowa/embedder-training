#!/usr/bin/env python
"""Configs for steps C and E of docs/PLAN-2026-10-27.md (queue_v12), one per teacher-score
normalisation so the queue can pick the one that won step B:

  mmse_fiqa_v3plus_<norm>.yaml            C: margin-MSE on fiqa-2073-v3-plus (extra synthetic positives)
  mmse_fiqa_v3_<norm>_docreg3e-4.yaml     E: document FLOPS weight 0.0003 instead of 0.001
  mmse_fiqa_v3_<norm>_docreg3e-3.yaml     E: document FLOPS weight 0.003
  mmse_fiqa_v3_<norm>_hardlowcov.yaml     E: only the hard + lowcov half of the rows (1357 queries)

Everything else is the recipe of configs/next/3060/mmse_fiqa_v3_<norm>.yaml (step B):
sdadas/polish-splade, lr 2e-5, 2 epochs, 512 tokens, 10 negatives, batch 2 x 16.
"""

from __future__ import annotations

from pathlib import Path

TEMPLATE = """backend: sentence-transformers
training_type: splade

# {desc}
# Generated by scripts/build_mmse_v3_configs.py; recipe of mmse_fiqa_v3_{norm}.yaml otherwise.
# score_normalization: {norm_value}
runs_dir: runs/arm-{name}
timestamp_output_dir: true
save_resolved_config: true

train_data: {data}

architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 2
    document_regularizer_weight: {docreg}
    loss: sparse_margin_mse

sentence_transformers:
  max_seq_length: 512
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: 2
  batch_sampler: no_duplicates
  gradient_accumulation_steps: 16
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 8
  negatives_per_query: 10
  score_normalization: {norm_value}
  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""

NORMS = {"none": "none", "minmax": "per_query_minmax", "zscore": "per_query_zscore"}
V3 = "datasets/arms/fiqa-2073-v3.jsonl"
VARIANTS = [
    # (config file stem, arm name, train data, docreg, description)
    ("mmse_fiqa_v3plus_{norm}", "mmse-fiqa-v3plus-{norm}", "datasets/arms/fiqa-2073-v3-plus.jsonl", "0.001",
     "Step C: the same 2073 queries with the extra synthetic positives of the MINE_POSITIVES export."),
    ("mmse_fiqa_v3_{norm}_docreg3e-4", "mmse-fiqa-v3-{norm}-docreg3e-4", V3, "0.0003",
     "Step E: weaker document FLOPS regularisation (0.0003)."),
    ("mmse_fiqa_v3_{norm}_docreg3e-3", "mmse-fiqa-v3-{norm}-docreg3e-3", V3, "0.003",
     "Step E: stronger document FLOPS regularisation (0.003)."),
    ("mmse_fiqa_v3_{norm}_hardlowcov", "mmse-fiqa-v3-{norm}-hardlowcov", "datasets/arms/fiqa-2073-v3-hardlowcov.jsonl",
     "0.001", "Step E: only the hard + lowcov half of the rows (query ids of datasets/arms/splits/fiqa-hard + fiqa-lowcov)."),
]


def main() -> None:
    out_dir = Path("configs/next/3060")
    out_dir.mkdir(parents=True, exist_ok=True)
    for norm, norm_value in NORMS.items():
        for stem, name, data, docreg, desc in VARIANTS:
            path = out_dir / f"{stem.format(norm=norm)}.yaml"
            path.write_text(
                TEMPLATE.format(desc=desc, norm=norm, norm_value=norm_value, name=name.format(norm=norm), data=data,
                                docreg=docreg),
                encoding="utf-8",
            )
            print(path)


if __name__ == "__main__":
    main()
