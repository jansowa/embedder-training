#!/usr/bin/env python
"""Arms drawn from the full FiQA-PL pool (5500 queries) without the reranker gate.

Tests whether selecting rows by base-model difficulty beats the score gate
(> 23.50 on the stronger reranker) that produced fiqa-2073:

  fiqa-pool-rand-2073   2073 random pool rows            (no gate, no selection)
  fiqa-pool-hard-2073   the 2073 pool rows with the highest base loss_own
  fiqa-pool-gate+hard   gate-passing rows first, ranked by loss_own, topped up
                        from the rest by loss_own to 2073 (gate AND difficulty)

Needs results/base_loss/fiqa-pool-5500.jsonl from
  scripts/splade_pair_loss.py --input datasets/arms/pool/fiqa-pool-5500.jsonl --n 0 --per-row-dir results/base_loss
Configs go to configs/weekend/pool/ (ck-warmup-s recipe, 2 epochs, no dataset_filter).
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

TEMPLATE = """backend: sentence-transformers
training_type: splade

# Pool arm generated by scripts/build_pool_arms.py: {desc}
runs_dir: runs/arm-{name}
timestamp_output_dir: true
save_resolved_config: true

train_data: datasets/arms/pool/{name}.jsonl

architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 2
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 256
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: 4
  batch_sampler: no_duplicates
  gradient_accumulation_steps: 8
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 32
  negatives_per_query: 6
  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def read_jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.open(encoding="utf-8") if l.strip()]


def gate_ok(r: dict, thr: float = 23.5) -> bool:
    s = r.get("pos_scores_stronger_reranker") or r.get("pos_scores") or []
    return bool(s) and s[0] is not None and float(s[0]) > thr


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool", type=Path, default=Path("datasets/arms/pool/fiqa-pool-5500.jsonl"))
    ap.add_argument("--loss", type=Path, default=Path("results/base_loss/fiqa-pool-5500.jsonl"))
    ap.add_argument("--n", type=int, default=2073)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--config-dir", type=Path, default=Path("configs/weekend/pool"))
    args = ap.parse_args()
    rows = read_jsonl(args.pool)
    for r in rows:
        r["query_id"] = str(r["query_id"])
    # The pool carries a few rows whose first positive (or a negative) is an
    # empty string; without the score gate they reach the loader, which rejects
    # them. Dropping the rows keeps pos/neg aligned with their score lists.
    def texts_ok(v: object) -> bool:
        return isinstance(v, list) and bool(v) and all(isinstance(x, str) and x.strip() for x in v)

    before = len(rows)
    rows = [r for r in rows if r.get("query") and texts_ok(r.get("pos")) and texts_ok(r.get("neg")) and len(r["neg"]) >= 6]
    print(f"pool: {len(rows)} usable rows of {before} ({before - len(rows)} dropped: empty texts or < 6 negatives)")
    loss = {str(x["query_id"]): float(x["loss_own"]) for x in read_jsonl(args.loss)} if args.loss.exists() else {}
    rng = random.Random(args.seed)
    plans = {}
    shuffled = rows[:]; rng.shuffle(shuffled)
    plans["fiqa-pool-rand-2073"] = ("random pool rows, no gate", shuffled[: args.n])
    if loss:
        by_loss = sorted((r for r in rows if r["query_id"] in loss), key=lambda r: (-loss[r["query_id"]], r["query_id"]))
        plans["fiqa-pool-hard-2073"] = ("highest base loss_own, no gate", by_loss[: args.n])
        gated = [r for r in by_loss if gate_ok(r)]
        rest = [r for r in by_loss if not gate_ok(r)]
        plans["fiqa-pool-gate-hard-2073"] = ("gate-passing rows ranked by loss_own, topped up by loss_own", (gated + rest)[: args.n])
    else:
        print("no base-loss file; only the random pool arm is built")
    args.config_dir.mkdir(parents=True, exist_ok=True)
    for name, (desc, chosen) in plans.items():
        chosen = chosen[:]; random.Random(args.seed + 1).shuffle(chosen)
        out = args.pool.parent / f"{name}.jsonl"
        with out.open("w", encoding="utf-8") as fh:
            for r in chosen:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
        (args.config_dir / f"arm_{name.replace('-', '_')}.yaml").write_text(TEMPLATE.format(name=name, desc=desc))
        g = sum(gate_ok(r) for r in chosen)
        med = sorted(loss[r["query_id"]] for r in chosen if r["query_id"] in loss)
        print(f"{name}: {len(chosen)} rows, gate-passing {g}, loss_own median {med[len(med)//2] if med else float('nan'):.4f} -> {out}")


if __name__ == "__main__":
    main()
