#!/usr/bin/env python
"""Turn judged arm files into clean / rejected training arms and configs.

Input: the output of scripts/judge_pairs.py for an arm (rows with "judge" and
"clean"). For each arm it writes

  datasets/arms/judged/<arm>-clean.jsonl      rows whose pos[0] passed the policy
  datasets/arms/judged/<arm>-rejected.jsonl   rows whose pos[0] failed it
  configs/weekend/judged/arm_<arm>_clean.yaml (+ _rejected) with the ck-warmup-s
  recipe and the epoch count scaled so that the optimizer-step count stays close
  to the 2073-row / 2-epoch arms (steps = rows * epochs / 32 ~ 130)
  results/judge/<arm>.report.json             axis rates and the policy used

Policies (--policy):
  clean      odpowiadalne & polszczyzna & sensowne_zapytanie & !zbyt_ogolne (weekend definition)
  answerable odpowiadalne only (the axis that carries most of the signal)
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

TEMPLATE = """backend: sentence-transformers
training_type: splade

# Judged arm generated by scripts/build_clean_arms.py: {desc}
# {rows} rows at {epochs} epochs (~{steps} optimizer steps at effective batch 32).
runs_dir: runs/arm-{name}
timestamp_output_dir: true
save_resolved_config: true

train_data: datasets/arms/judged/{name}.jsonl

dataset_filter: configs/dataset_filters/splade_positive_score_gt_23_50_no_metricx.yaml
dataset_filter_cache_dir: cache/filtered_datasets

architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: {epochs}
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 256
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: 4
  batch_sampler: no_duplicates
  gradient_accumulation_steps: 8
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 32
  negatives_per_query: 6
  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def passes(v: dict | None, policy: str) -> bool | None:
    if v is None:
        return None
    if policy == "answerable":
        return bool(v["odpowiadalne"])
    return bool(v["odpowiadalne"] and v["polszczyzna"] and v["sensowne_zapytanie"] and not v["zbyt_ogolne"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--judged", nargs="+", required=True, type=Path, help="judge_pairs.py outputs, e.g. results/judge/trivia-2073.judged.jsonl")
    ap.add_argument("--policy", choices=("clean", "answerable"), default="clean")
    ap.add_argument("--target-steps", type=int, default=130)
    ap.add_argument("--min-rows", type=int, default=300)
    ap.add_argument("--out-dir", type=Path, default=Path("datasets/arms/judged"))
    ap.add_argument("--config-dir", type=Path, default=Path("configs/weekend/judged"))
    ap.add_argument("--report-dir", type=Path, default=Path("results/judge"))
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    args.config_dir.mkdir(parents=True, exist_ok=True)
    args.report_dir.mkdir(parents=True, exist_ok=True)

    for path in args.judged:
        arm = path.name.split(".")[0]
        rows = [json.loads(l) for l in path.open(encoding="utf-8") if l.strip()]
        clean, rejected, unjudged = [], [], 0
        axes = {"odpowiadalne": 0, "polszczyzna": 0, "sensowne_zapytanie": 0, "zbyt_ogolne": 0}
        problems: dict[str, int] = {}
        for r in rows:
            v = (r.get("judge") or {}).get("pos", [None])[0]
            ok = passes(v, args.policy)
            if ok is None:
                unjudged += 1; continue
            for a in axes:
                axes[a] += int(v[a])
            problems[v.get("glowny_problem", "")] = problems.get(v.get("glowny_problem", ""), 0) + 1
            slim = {k: r[k] for k in r if k not in ("judge", "clean")}
            (clean if ok else rejected).append(slim)
        n_j = len(clean) + len(rejected)
        report = {"arm": arm, "policy": args.policy, "rows": len(rows), "judged": n_j, "unjudged": unjudged,
                  "clean": len(clean), "rejected": len(rejected), "clean_rate": (len(clean) / n_j) if n_j else None,
                  "axis_true_rate": {a: (axes[a] / n_j) if n_j else None for a in axes}, "glowny_problem": problems}
        (args.report_dir / f"{arm}.report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False))
        print(f"{arm}: judged {n_j}/{len(rows)}, {args.policy} {len(clean)} ({100 * (report['clean_rate'] or 0):.1f}%), "
              + ", ".join(f"{a}={100 * (report['axis_true_rate'][a] or 0):.0f}%" for a in axes))
        for tag, subset in (("clean", clean), ("rejected", rejected)):
            name = f"{arm}-{tag}"
            if len(subset) < args.min_rows:
                print(f"  {name}: only {len(subset)} rows, no arm written"); continue
            out = args.out_dir / f"{name}.jsonl"
            with out.open("w", encoding="utf-8") as fh:
                for r in subset:
                    fh.write(json.dumps(r, ensure_ascii=False) + "\n")
            epochs = max(1, min(8, round(args.target_steps * 32 / len(subset))))
            steps = round(len(subset) * epochs / 32)
            cfg = args.config_dir / f"arm_{name.replace('-', '_')}.yaml"
            cfg.write_text(TEMPLATE.format(name=name, desc=f"pos[0] {'passed' if tag == 'clean' else 'failed'} policy '{args.policy}'",
                                           rows=len(subset), epochs=epochs, steps=steps))
            print(f"  {name}: {len(subset)} rows -> {out}, {epochs} epochs (~{steps} steps) -> {cfg}")


if __name__ == "__main__":
    main()
