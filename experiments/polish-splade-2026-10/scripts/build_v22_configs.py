#!/usr/bin/env python
"""Configs for queue v22 (night 29/30.10 and the day of 30.10 on the 3060 Ti).

All arms use the arm-cluster-like-fiqa recipe (MNRL + FLOPS, lr 2e-5, 2 epochs, 512 tokens,
10 negatives, docreg 0.001, query reg 5e-5), as in configs/next/3060/mnrl_fiqa_splade_*.yaml.

  ctrl-cb32        the cluster-like rows (fiqa-2073 with the gate filter) at a TRUE batch of 32
                   queries through CachedSpladeLoss (GradCache, mini-batch 4) instead of 2 x 16
                   accumulation. Measures the batch regime itself against arm-cluster-like-fiqa
                   (62.27 tiny, 40.17 held-out, 396 dims/doc). FLOPS now runs over the whole
                   batch, so the sparsity may drop: watch dims/doc.
  ldose1/2/4       1, 2 or 4 long-easy negatives (outside the SPLADE top-100, longer than the
                   query's longest positive) + 9, 8 or 6 old v3 negatives per query
                   (scripts/build_fiqa_mix_negatives.py). The moderate length correction:
                   long-easy-5070 alone wins arguana-pl by 10 and loses fiqa-pl by 8.
  lenmatch-*       student-mined negatives drawn inside a length window around the positives
                   (scripts/build_fiqa_band_negatives.py --len-window 0.7 1.4): hard (the 10
                   hardest for the student inside the window), far (more than 3 below the
                   best positive, random), and hard x2 + 8 old (mix2). Separates "hard" from
                   "long": every earlier band was 3x longer than the old negatives. (Ranks
                   1-20 inside the window hold only 3-4 negatives per query, so a rank band
                   would be backfilled to the depth of far.)
  *_cb32           fallback of the same arm with CachedSpladeLoss (batch 32, mini-batch 2),
                   used by the queue only when the 2 x 16 run fails (CUDA OOM on long
                   negatives). Same runs_dir, so the queue finds the checkpoint either way.

Files: configs/next/3060/mnrl_fiqa_<name>.yaml; arms models/arm-mnrl-fiqa-<name>.
"""

from __future__ import annotations

from pathlib import Path

OUT = Path("configs/next/3060")
FILTER = ("dataset_filter: configs/dataset_filters/splade_positive_score_gt_23_50_no_metricx.yaml\n"
          "dataset_filter_cache_dir: cache/filtered_datasets\n")


def config(tag: str, desc: str, data: str, batch: int, accum: int, cached_mini: int | None, filter_lines: str = "") -> str:
    cached = f"  cached_loss: true\n  mini_batch_size: {cached_mini}\n" if cached_mini else ""
    return f"""backend: sentence-transformers
training_type: splade

# {desc}
# Generated by scripts/build_v22_configs.py.
runs_dir: runs/arm-{tag}
timestamp_output_dir: true
save_resolved_config: true

train_data: {data}
{filter_lines}
architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 2
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 512
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: {batch}
  batch_sampler: no_duplicates
  gradient_accumulation_steps: {accum}
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 8
  negatives_per_query: 10
{cached}  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def write(name: str, text: str) -> None:
    path = OUT / f"mnrl_fiqa_{name.replace('-', '_')}.yaml"
    path.write_text(text, encoding="utf-8")
    print(path)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    recipe = "recipe mnrl (cluster-like), 512 tokens, 10 negatives"
    write("ctrl-cb32", config("mnrl-fiqa-ctrl-cb32",
                               f"Batch control: the arm-cluster-like-fiqa rows (gate filter) at a true batch of 32 queries via CachedSpladeLoss (mini-batch 4); {recipe}.",
                               "datasets/arms/fiqa-2073.jsonl", 32, 1, 4, FILTER))
    arms = {
        "ldose1": ("1 long-easy + 9 old v3 negatives per query (moderate length correction)", "datasets/arms/fiqa-2073-ldose1.jsonl"),
        "ldose2": ("2 long-easy + 8 old v3 negatives per query (moderate length correction)", "datasets/arms/fiqa-2073-ldose2.jsonl"),
        "ldose4": ("4 long-easy + 6 old v3 negatives per query (moderate length correction)", "datasets/arms/fiqa-2073-ldose4.jsonl"),
        "lenmatch-hard": ("the 10 hardest student negatives (highest SPLADE margin) inside the length window 0.7-1.4 x the positives", "datasets/arms/fiqa-2073-splade-band-hard-lenmatch.jsonl"),
        "lenmatch-far": ("student negatives more than 3 below the best positive (random), inside the length window 0.7-1.4 x the positives", "datasets/arms/fiqa-2073-splade-band-far-lenmatch.jsonl"),
        "lenmatch-hard-mix2": ("the 2 hardest length-matched student negatives + 8 old v3 negatives per query", "datasets/arms/fiqa-2073-splade-lenmatch-hard-mix2.jsonl"),
    }
    for name, (desc, data) in arms.items():
        tag = f"mnrl-fiqa-{name}"
        write(name, config(tag, f"{desc}; {recipe}, batch 2 x 16, pooling chunk 8.", data, 2, 16, None))
        write(f"{name}-cb32", config(tag, f"{desc}; {recipe}, fallback: CachedSpladeLoss at batch 32 (mini-batch 2) when 2 x 16 runs out of memory.", data, 32, 1, 2))


if __name__ == "__main__":
    main()
