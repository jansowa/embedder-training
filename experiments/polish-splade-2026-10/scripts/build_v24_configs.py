#!/usr/bin/env python
"""Configs for queue v24 (morning of 31.10 on the 3060 Ti, after queue v23).

  seed3, seed4     seeds 3 and 4 of the reference recipe (see build_v23_configs.py), so the
                   per-task noise table has five seeds (42, 1, 2, 3, 4).
  smoke-*          CachedSpladeLoss speed probes: the cluster-like recipe at a true batch of 32,
                   three optimizer steps, mini-batch 4 / 8 / 16 with and without gradient
                   checkpointing. Only step time and peak memory are read from them.

Files: configs/next/3060/mnrl_fiqa_seed{3,4}.yaml (+ _cb32) and configs/next/3060/smoke_cb32_mb*.yaml.
"""

from __future__ import annotations

from pathlib import Path

from build_v23_configs import FILTER, OUT, config, write


def smoke(mini: int, checkpointing: bool) -> str:
    tag = f"cb32-mb{mini}-{'gc' if checkpointing else 'nogc'}"
    return f"""backend: sentence-transformers
training_type: splade

# GradCache speed probe: the cluster-like recipe at a true batch of 32 queries, mini-batch {mini},
# gradient checkpointing {'on' if checkpointing else 'off'}, three optimizer steps, no logging.
# Generated by scripts/build_v24_configs.py.
runs_dir: runs/smoke-{tag}
timestamp_output_dir: true
save_resolved_config: true

train_data: datasets/arms/fiqa-2073.jsonl

{FILTER}
architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 1
    max_steps: 3
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 512
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: 32
  batch_sampler: no_duplicates
  gradient_accumulation_steps: 1
  gradient_checkpointing: {'true' if checkpointing else 'false'}
  fp16: true
  splade_pooling_chunk_size: 8
  negatives_per_query: 10
  cached_loss: true
  mini_batch_size: {mini}
  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to: []
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    recipe = "recipe mnrl (cluster-like), 512 tokens, 10 negatives, batch 2 x 16, pooling chunk 8"
    for s in (3, 4):
        write(f"mnrl_fiqa_seed{s}", config(f"mnrl-fiqa-seed{s}",
                                          f"Seed {s} of the reference arm-cluster-like-fiqa (gate filter, default seed 42); {recipe}.",
                                          "datasets/arms/fiqa-2073.jsonl", 2, 16, None, FILTER, seed=s))
        write(f"mnrl_fiqa_seed{s}_cb32", config(f"mnrl-fiqa-seed{s}",
                                               f"Seed {s} of the reference; fallback: CachedSpladeLoss at batch 32 (mini-batch 2).",
                                               "datasets/arms/fiqa-2073.jsonl", 32, 1, 2, FILTER, seed=s))
    for mini in (4, 8, 16):
        for gc in (True, False):
            path = OUT / f"smoke_cb32_mb{mini}_{'gc' if gc else 'nogc'}.yaml"
            path.write_text(smoke(mini, gc), encoding="utf-8")
            print(path)


if __name__ == "__main__":
    main()
