#!/usr/bin/env python
"""Configs for queue v23 (night 30/31.10 on the 3060 Ti).

  seed1, seed2     the reference recipe (arm-cluster-like-fiqa: fiqa-2073 rows with the gate
                   filter, MNRL + FLOPS, 2 x 16, 512 tokens, 10 negatives) with seeds 1 and 2
                   (the reference ran with the default seed 42). Gives the per-task noise
                   floor on tiny and held-out-8, which decides whether the task-by-task
                   wins and losses between arms are real.
  n1-ldose2        the n1 recipe (FiQA 2073 + SQuAD-v2 2073) with the FiQA rows replaced by
                   the 2-long-easy dose rows (datasets/arms/fiqa-ldose2-plus-squadv2.jsonl),
                   trained at 2 x 16 on the 3060 (n1 itself: 8 x 4 on the 5070 Ti). Tests
                   the dose inside the recipe that feeds the soups.
  *_cb32           CachedSpladeLoss fallback (batch 32, mini-batch 2), used only after an OOM.

Files: configs/next/3060/mnrl_fiqa_seed{1,2}.yaml, configs/next/3060/n1_ldose2.yaml (+ _cb32).
"""

from __future__ import annotations

from pathlib import Path

OUT = Path("configs/next/3060")
FILTER = ("dataset_filter: configs/dataset_filters/splade_positive_score_gt_23_50_no_metricx.yaml\n"
          "dataset_filter_cache_dir: cache/filtered_datasets\n")


def config(tag: str, desc: str, data: str, batch: int, accum: int, cached_mini: int | None,
           filter_lines: str = "", seed: int | None = None) -> str:
    cached = f"  cached_loss: true\n  mini_batch_size: {cached_mini}\n" if cached_mini else ""
    seed_line = f"  seed: {seed}\n" if seed is not None else ""
    return f"""backend: sentence-transformers
training_type: splade

# {desc}
# Generated by scripts/build_v23_configs.py.
runs_dir: runs/arm-{tag}
timestamp_output_dir: true
save_resolved_config: true

train_data: {data}
{filter_lines}
architectures:
  - sdadas/polish-splade

hparams:
  - learning_rate: 2e-5
    num_train_epochs: 2
    document_regularizer_weight: 0.001
    loss: sparse_multiple_negatives_ranking

sentence_transformers:
  max_seq_length: 512
  warmup_ratio: 0.1
  lr_scheduler_type: linear
  train_batch_size: {batch}
  batch_sampler: no_duplicates
  gradient_accumulation_steps: {accum}
  gradient_checkpointing: true
  fp16: true
  splade_pooling_chunk_size: 8
  negatives_per_query: 10
{cached}{seed_line}  save_strategy: "no"
  keep_epoch_checkpoints: false
  report_to:
    - wandb
  query_regularizer_weight: 0.00005

benchmark:
  run_pirb: false
  scope: tiny
  max_seq_length: 512
  query_instruction: ""
  checkpoints:
    - final
"""


def write(name: str, text: str) -> None:
    path = OUT / f"{name}.yaml"
    path.write_text(text, encoding="utf-8")
    print(path)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    recipe = "recipe mnrl (cluster-like), 512 tokens, 10 negatives, batch 2 x 16, pooling chunk 8"
    for s in (1, 2):
        write(f"mnrl_fiqa_seed{s}", config(f"mnrl-fiqa-seed{s}",
                                          f"Seed {s} of the reference arm-cluster-like-fiqa (gate filter, default seed 42); {recipe}.",
                                          "datasets/arms/fiqa-2073.jsonl", 2, 16, None, FILTER, seed=s))
        write(f"mnrl_fiqa_seed{s}_cb32", config(f"mnrl-fiqa-seed{s}",
                                               f"Seed {s} of the reference; fallback: CachedSpladeLoss at batch 32 (mini-batch 2).",
                                               "datasets/arms/fiqa-2073.jsonl", 32, 1, 2, FILTER, seed=s))
    # No gate filter here: the dose rows carry SPLADE pos_scores (not the reranker scale), so the
    # gate would drop them all; the SQuAD rows were gated (> 23.50) when the file was built.
    desc = "n1 recipe (FiQA 2073 + SQuAD-v2 2073 pre-gated) with the FiQA rows replaced by the 2-long-easy dose rows"
    write("n1_ldose2", config("n1-ldose2", f"{desc}; {recipe}.", "datasets/arms/fiqa-ldose2-plus-squadv2.jsonl", 2, 16, None))
    write("n1_ldose2_cb32", config("n1-ldose2", f"{desc}; fallback: CachedSpladeLoss at batch 32 (mini-batch 2).",
                                   "datasets/arms/fiqa-ldose2-plus-squadv2.jsonl", 32, 1, 2))


if __name__ == "__main__":
    main()
